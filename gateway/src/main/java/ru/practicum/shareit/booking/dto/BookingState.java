package ru.practicum.shareit.booking.dto;

import java.util.Optional;

/**
 * Перечисление состояний бронирования (Booking).
 * Определяет возможные статусы бронирования в системе,
 * включая текущие, будущие, завершённые и отклоненные бронирования,
 * а также бронирования, ожидающие подтверждения.
 */

public enum BookingState {

    /**
     * Все бронирования без фильтрации по статусу.
     * Используется для запросов, требующих получения полной истории бронирований.
     */
    ALL,

    /**
     * Текущие бронирования — находятся в активном периоде (начало уже наступило,
     * конец ещё не наступил).
     */
    CURRENT,

    /**
     * Будущие бронирования — запланированные бронирования, период которых
     * ещё не начался (дата начала в будущем).
     */
    FUTURE,

    /**
     * Завершённые бронирования — бронирования, период которых полностью истёк
     * (дата окончания уже прошла).
     */
    PAST,

    /**
     * Отклонённые бронирования — запросы на бронирование, которые были отклонены
     * владельцем ресурса.
     */
    REJECTED,

    /**
     * Ожидающие подтверждения бронирования — новые запросы на бронирование,
     * которые ещё не были подтверждены или отклонены владельцем ресурса.
     */
    WAITING;

    /**
     * Преобразует строковое представление состояния бронирования в соответствующее
     * значение перечисления.
     * Поиск выполняется с игнорированием регистра символов. Если строка не соответствует
     * ни одному из известных состояний, возвращается пустой Optional.
     *
     * @param stringState строковое представление состояния бронирования
     *                    (например, "ALL", "current", "FUTURE" и т. д.)
     * @return {@link Optional} с соответствующим значением {@link BookingState},
     * если строка распознана; {@link Optional#empty()}, если строка не соответствует
     * ни одному известному состоянию
     * @throws NullPointerException если параметр {@code stringState} равен {@code null}
     */

    public static Optional<BookingState> from(String stringState) {
        for (BookingState state : values()) {
            if (state.name().equalsIgnoreCase(stringState)) {
                return Optional.of(state);
            }
        }
        return Optional.empty();
    }
}
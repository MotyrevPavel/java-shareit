package ru.practicum.shareit.user.dto;

import lombok.Builder;
import lombok.Data;

/**
 * Data Transfer Object (DTO) для передачи данных об обновлениях пользователя.
 * Используется в API для частичной модификации данных пользователя. Позволяет обновлять
 * имя и/или email независимо друг от друга. Поля, которые не переданы (null),
 * игнорируются при обновлении.
 * Особенности класса:
 * Использует Lombok {@link lombok.Data} для автоматической генерации:
 * геттеров и сеттеров
 * методов {@code equals()} и {@code hashCode()}
 * метода {@code toString()}
 * Поддерживает валидацию email через аннотацию Jakarta Validation
 * Содержит вспомогательные методы для проверки наличия данных
 * Предназначен исключительно для передачи данных (не содержит бизнес‑логики)
 */

@Data
@Builder
public class UpdateUser {

    /**
     * Новое имя пользователя.
     * Опциональное поле. Если передано (не null), будет использовано для обновления.
     * Если равно null, имя пользователя не изменяется.
     * Требования к значению:
     * длина и формат не ограничены на уровне DTO
     */
    private String name;

    /**
     * Новый адрес электронной почты пользователя.
     * Опциональное поле. Если передано (не null), пройдёт валидацию как email
     * и будет использовано для обновления. Если равно null, email не изменяется.
     * Требования к значению:
     * если не null, должен быть корректным email‑адресом
     * обычно проверяется на уникальность на уровне сервиса
     * Пример корректного значения: {@code user@example.com}</p>
     */
    private String email;

    /**
     * Проверяет, указано ли новое имя пользователя в запросе на обновление.
     *
     * @return {@code true}, если поле {@code name} не равно null (имя передано для обновления);
     * {@code false}, если поле {@code name} равно null (изменение имени не требуется)
     */
    public boolean hasName() {
        return name != null;
    }

    /**
     * Проверяет, указан ли новый email пользователя в запросе на обновление.
     *
     * @return {@code true}, если поле {@code email} не равно null (email передан для обновления);
     * {@code false}, если поле {@code email} равно null (изменение email не требуется)
     */
    public boolean hasEmail() {
        return email != null;
    }
}

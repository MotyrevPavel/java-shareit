package ru.practicum.shareit.item.dto;

import lombok.Builder;
import lombok.Data;
import ru.practicum.shareit.booking.dto.BookingDto;
import ru.practicum.shareit.item.comment.dto.CommentDto;
import ru.practicum.shareit.item.model.Item;

import java.util.List;

/**
 * Data Transfer Object (DTO) для передачи полной информации о предмете между слоями приложения.
 * <p>
 * Используется для:
 * <ul>
 *   <li>формирования развёрнутого ответа API при получении информации о конкретном предмете;</li>
 *   <li>передачи данных между контроллером, сервисом и другими компонентами;</li>
 *   <li>сериализации в JSON при HTTP‑ответах, включающих связанные сущности.</li>
 * </ul>
 *
 * <p>Отличается от сущности {@link Item} тем, что:
 * <ul>
 *   <li>не содержит бизнес‑логики;</li>
 *   <li>служит исключительно для транспортировки данных;</li>
 *   <li>включает связанные данные (последнее/следующее бронирование, комментарии),
 *       которые отсутствуют в базовой сущности;</li>
 *   <li>может быть адаптирован под конкретные API‑ответы (например, исключать поля
 *       при частичном представлении).</li>
 * </ul>
 *
 * <p>Типичный сценарий использования — отображение страницы предмета с:
 * <ul>
 *   <li>основной информацией (название, описание, доступность);</li>
 *   <li>предстоящим и последним бронированием (для понимания графика использования);</li>
 *   <li>списком комментариев (для оценки репутации и состояния предмета).</li>
 * </ul>
 *
 * @see Item базовая сущность предмета в системе
 * @see BookingDto DTO для представления информации о бронировании
 * @see CommentDto DTO для представления комментария к предмету
 */

@Data
@Builder
public class ItemFullDto {

    /**
     * Уникальный идентификатор предмета в системе.
     *
     * <p>Генерируется автоматически при создании предмета. Используется для однозначной
     * идентификации и ссылок в других сущностях (например, в бронированиях или комментариях).
     *
     * <p>Особенности:
     * <ul>
     *   <li>не может быть {@code null} для сохранённых предметов;</li>
     *   <li>используется в URL API (например, {@code /items/{id}});</li>
     *   <li>остаётся неизменным на протяжении жизненного цикла предмета.</li>
     * </ul>
     */
    private Long id;

    /**
     * Название предмета.
     *
     * <p>Краткое, информативное наименование, позволяющее пользователю быстро
     * идентифицировать предмет. Отображается в списках и карточках предметов.
     *
     * <p>Требования:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>не должен быть пустой строкой;</li>
     * </ul>
     */
    private String name;

    /**
     * Подробное описание предмета.
     *
     * <p>Содержит развёрнутую информацию о предмете
     *
     * <p>Требования:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>может быть длинной строкой с переносами строк;</li>
     * </ul>
     */
    private String description;

    /**
     * Статус доступности предмета для аренды.
     *
     * <p>Указывает, может ли пользователь создать бронирование для этого предмета.
     * Управляется владельцем предмета через интерфейс системы.
     *
     * <p>Возможные значения:
     * <ul>
     *   <li>{@code true} — предмет доступен для бронирования (по умолчанию);</li>
     *   <li>{@code false} — предмет временно не доступен.</li>
     * </ul>
     *
     * <p>Используется для:
     * <ul>
     *   <li>фильтрации доступных предметов в поиске;</li>
     *   <li>блокировки создания бронирований для недоступных предметов;</li>
     *   <li>отображения статуса в интерфейсе (зелёная метка «Доступно» / красная «Недоступно»).</li>
     * </ul>
     */
    private Boolean available;

    /**
     * Идентификатор пользователя‑владельца предмета.
     *
     * <p>Связывает предмет с конкретным пользователем в системе. Определяет права доступа:
     * только владелец может редактировать предмет, управлять его доступностью,
     * подтверждать бронирования и т.д.
     *
     * <p>Особенности:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>должен соответствовать существующему пользователю;</li>
     *   <li>не редактируется после создания предмета.</li>
     * </ul>
     */
    private Long userId;

    /**
     * Информация о следующем предстоящем бронировании предмета.
     *
     * <p>Отображает ближайшее по времени бронирование, которое ещё не началось.
     * Позволяет арендаторам и владельцу оценить график использования предмета.
     *
     * <p>Может быть {@code null}, если:
     * <ul>
     *   <li>у предмета нет будущих бронирований;</li>
     *   <li>все бронирования завершены или отменены.</li>
     * </ul>
     *
     * <p>Используется для:
     * <ul>
     *   <li>отображения «окна доступности» между бронированиями;</li>
     *   <li>предотвращения конфликтов дат при создании новых бронирований;</li>
     *   <li>визуализации календаря использования предмета.</li>
     * </ul>
     *
     * @see BookingDto DTO с информацией о бронировании
     */
    private BookingDto nextBooking;

    /**
     * Информация о последнем будущем бронировании предмета.
     *
     * <p>Отображает самое последнее по времени бронирование, которое будет в будущем.
     * Помогает оценить актуальность и востребованность предмета.
     *
     * <p>Может быть {@code null}, если:
     * <ul>
     *   <li>предмет новый и никогда не бронировался;</li>
     *   <li>все бронирования ещё ожидают подтверждения.</li>
     * </ul>
     *
     * <p>Используется для:
     * <ul>
     *   <li>отображения истории использования;</li>
     *   <li>расчёта рейтинга предмета на основе отзывов после бронирований;</li>
     *   <li>анализа популярности категории предметов.</li>
     * </ul>
     *
     * @see BookingDto DTO с информацией о бронировании
     */
    private BookingDto lastBooking;

    /**
     * Список комментариев, оставленных пользователями о предмете.
     *
     * <p>Содержит отзывы арендаторов и других пользователей, которые ранее
     * взаимодействовали с предметом.
     *
     * <p>Особенности:
     * <ul>
     *   <li>может быть пустым списком, если комментариев ещё нет;</li>
     *   <li>сортируется по дате создания в порядке убывания
     *       (новые комментарии сверху);</li>
     *   <li>каждый элемент списка — экземпляр {@link CommentDto}, содержащий
     *       текст комментария, имя автора и дату создания;</li>
     * </ul>
     *
     * <p>Требования:
     * <ul>
     *   <li>не может быть {@code null} — если комментариев нет, возвращается
     *       пустой список ({@code Collections.emptyList()} или {@code new ArrayList<>()});</li>
     * </ul>
     *
     * @see CommentDto DTO с информацией о комментарии к предмету
     */
    private List<CommentDto> comments;
}

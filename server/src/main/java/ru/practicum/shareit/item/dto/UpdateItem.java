package ru.practicum.shareit.item.dto;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Модель данных для частичного обновления предмета в системе аренды.
 * Используется при:
 * отправке HTTP‑запроса на частичное обновление предмета (PATCH);
 * валидации входных данных перед применением изменений;
 * передаче данных из контроллера в сервисный слой.
 * Особенности:
 * все поля могут быть null (обновление только указанных полей);
 * строковые поля ({@link #name}, {@link #description}) валидируются только если не null;
 * поле {@link #available} может быть null — означает, что статус доступности не меняется.
 */

@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
public class UpdateItem {

    /**
     * Новое название предмета.
     * Условия валидации:
     * если значение не null — должно быть не пустым и содержать хотя бы один непробельный символ;
     * если значение null — поле игнорируется при обновлении.
     * Сообщение об ошибке при нарушении: "Имя вещи не может быть пустым или содержать только пробелы".
     * Пример корректного значения: "Обновлённое название стула".
     */
    private String name;

    /**
     * Новое описание предмета.
     * Условия валидации:
     * если значение не null — должно быть не пустым и содержать хотя бы один непробельный символ;
     * если значение null — поле игнорируется при обновлении.
     * Сообщение об ошибке при нарушении: "Описание не может быть пустым или содержать только пробелы".
     * Пример корректного значения: "Обновлённое описание предмета".
     */
    private String description;

    /**
     * Новый статус доступности предмета для аренды.
     * Условия:
     * может быть null — означает, что статус доступности не требуется менять;
     * если указано, должно быть явно true (доступно) или false (не доступно).
     * Значение устанавливает владелец предмета при обновлении записи.
     * Важно: null не вызывает ошибку валидации — это сигнал "не менять текущее значение".
     */
    private Boolean available; //Проставляет владелец

    /**
     * Проверяет, указано ли новое название предмета.
     *
     * @return true, если поле {@link #name} не null, иначе false
     */
    public boolean hasName() {
        return name != null;
    }

    /**
     * Проверяет, указано ли новое описание предмета.
     *
     * @return true, если поле {@link #description} не null, иначе false
     */
    public boolean hasDescription() {
        return description != null;
    }

    /**
     * Проверяет, указан ли новый статус доступности.
     *
     * @return true, если поле {@link #available} не null, иначе false
     */
    public boolean hasAvailable() {
        return available != null;
    }
}
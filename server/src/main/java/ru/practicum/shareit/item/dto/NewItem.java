package ru.practicum.shareit.item.dto;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import ru.practicum.shareit.item.ItemController;
import ru.practicum.shareit.item.ItemService;
import ru.practicum.shareit.item.model.Item;

/**
 * Модель данных для создания нового предмета в системе аренды.
 * Используется при:
 * отправке HTTP‑запроса на добавление предмета;
 * валидации входных данных перед сохранением;
 * передаче данных из контроллера в сервисный слой.
 * Особенности:
 * все поля обязательны для заполнения;
 * строковые поля проходят многоуровневую проверку (null, пусто, пробелы);
 * поле {@link #available} требует явного указания true/false (не допускает null).
 *
 * @see Item
 * @see ItemController
 * @see ItemService
 */

@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
public class NewItem {

    /**
     * Название предмета.
     * Требования к значению:
     * Пример: "Дрель", "Велосипед горный".
     */
    private String name;

    /**
     * Подробное описание предмета.
     * Требования к значению (аналогично полю {@link #name}):
     * не может быть null;
     * не может быть пустой строкой;
     * не может состоять только из пробелов.
     * Пример: "Стул из массива дуба, выдерживает нагрузку до 120 кг".
     */
    private String description;

    /**
     * Статус доступности предмета для аренды.
     * Требования:
     * обязательно указать значение
     * допустимы только {@code true} (доступно) или {@code false} (недоступно).
     * Значение устанавливает владелец предмета при создании записи.
     * Важно: null не допускается — необходимо явно указать статус.
     */
    private Boolean available;

    /**
     * Идентификатор запроса на аренду (требования), к которому привязан предмет.
     * Указывает, что предмет был добавлен или предложен в ответ на конкретный запрос пользователя
     * о поиске предмета для аренды. Связывает предмет с изначальной потребностью арендатора.
     * Особенности:
     * может быть {@code null}, если предмет добавлен в каталог без привязки к запросу
     * (например, владелец просто предлагает вещь в аренду);
     * если значение задано, должно соответствовать существующему запросу
     * на аренду ({@link ru.practicum.shareit.request.ItemRequest});
     * используется для реализации функционала «ответов на запросы»:
     * когда пользователи ищут предмет, система может предложить им подходящие
     * варианты от владельцев;
     *
     * @see ru.practicum.shareit.request.ItemRequest сущность запроса на аренду предмета
     */
    private Long requestId;
}
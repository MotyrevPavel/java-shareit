package ru.practicum.shareit.item.comment.dto;

import com.fasterxml.jackson.annotation.JsonFormat;
import lombok.Builder;
import lombok.Data;

import java.time.LocalDateTime;

/**
 * DTO для представления информации о комментарии к предмету в системе аренды.
 * <p>
 * Используется для:
 * <ul>
 *   <li>передачи данных о комментариях между слоями приложения;</li>
 *   <li>сериализации/десериализации в JSON при HTTP‑запросах;</li>
 *   <li>отображения информации о комментариях в пользовательском интерфейсе.</li>
 * </ul>
 *
 * <p>Особенности класса:
 * <ul>
 *   <li>содержит основную информацию о комментарии: текст, автора, дату создания;</li>
 *   <li>использует {@link Builder} для удобного создания экземпляров;</li>
 *   <li>дата создания форматируется в стандартизированном формате через {@link JsonFormat};</li>
 *   <li>поле {@link #id} может быть {@code null} для новых комментариев, которые ещё не сохранены в БД.</li>
 * </ul>
 *
 * @see JsonFormat для указания формата даты в JSON
 */

@Data
@Builder
public class CommentDto {
    /**
     * Уникальный идентификатор комментария в системе.
     *
     * <p>Генерируется на стороне сервера при сохранении комментария в БД.
     * Может быть {@code null} для новых комментариев, которые ещё не были созданы в системе.
     */
    private Long id;

    /**
     * Текст комментария, оставленный пользователем о предмете.
     *
     * <p>Содержит отзыв, оценку или дополнительную информацию о предмете,
     * которую пользователь хочет сообщить другим арендаторам или владельцу.
     *
     * <p>Требования:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>не должен быть пустой строкой;</li>
     * </ul>
     */
    private String text;

    /**
     * Имя пользователя, оставившего комментарий.
     *
     * <p>Отображается в интерфейсе рядом с текстом комментария для идентификации автора.
     * Обычно берётся из профиля пользователя и не редактируется при создании комментария.
     *
     * <p>Требования:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>не должен быть пустой строкой;</li>
     *   <li>может совпадать с именем пользователя в профиле.</li>
     * </ul>
     */
    private String authorName;

    /**
     * Дата и время создания комментария.
     *
     * <p>Указывает, когда комментарий был оставлен пользователем. Форматируется в JSON
     * по шаблону {@code yyyy-MM-dd'T'HH:mm:ss} (например: {@code 2023-12-25T10:00:00}).
     *
     * <p>Особенности:
     * <ul>
     *   <li>устанавливается автоматически на стороне сервера в момент сохранения комментария;</li>
     *   <li>не может быть {@code null} для сохранённых комментариев;</li>
     *   <li>не редактируется после создания.</li>
     * </ul>
     *
     * @see JsonFormat для указания формата даты в JSON
     */
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime created;
}

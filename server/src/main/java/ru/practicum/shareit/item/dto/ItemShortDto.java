package ru.practicum.shareit.item.dto;

import lombok.Builder;
import lombok.Data;

/**
 * Data Transfer Object (DTO) для краткого представления предмета в системе аренды.
 * <p>
 * Используется для:
 * <ul>
 *   <li>передачи минимальной информации о предмете между слоями приложения;</li>
 *   <li>сериализации в JSON при HTTP‑ответах, где не требуется полная информация;</li>
 *   <li>включения в другие DTO в качестве вложенного объекта.</li>
 * </ul>
 *
 * <p>Отличается от {@link ItemFullDto} тем, что:
 * <ul>
 *   <li>содержит только базовые поля (ID, название, владелец);</li>
 *   <li>не включает развёрнутое описание, статус доступности и связанные сущности
 *       (бронирования, комментарии);</li>
 * </ul>
 *
 * @see ItemFullDto DTO с полной информацией о предмете (описание, доступность, бронирования, комментарии)
 */

@Data
@Builder
public class ItemShortDto {

    /**
     * Уникальный идентификатор предмета в системе.
     *
     * <p>Генерируется автоматически при создании предмета. Используется для однозначной
     * идентификации и ссылок в других сущностях (например, в бронированиях).
     *
     * <p>Особенности:
     * <ul>
     *   <li>не может быть {@code null} для сохранённых предметов;</li>
     *   <li>используется в URL API (например, {@code /items/{id}});</li>
     *   <li>остаётся неизменным на протяжении жизненного цикла предмета;</li>
     *   <li>служит ключом для получения полной информации через {@link ItemFullDto}.</li>
     * </ul>
     */
    private Long id;

    /**
     * Название предмета.
     *
     * <p>Краткое, информативное наименование, позволяющее пользователю быстро
     * идентифицировать предмет. Отображается в списках и карточках предметов.
     *
     * <p>Требования:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>не должен быть пустой строкой;</li>
     * </ul>
     */
    private String name;

    /**
     * Идентификатор пользователя‑владельца предмета.
     *
     * <p>Связывает предмет с конкретным пользователем в системе. Определяет права доступа:
     * только владелец может редактировать предмет, управлять его доступностью,
     * подтверждать бронирования и т.д.
     *
     * <p>Особенности:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>должен соответствовать существующему пользователю;</li>
     *   <li>не редактируется после создания предмета;</li>
     *   <li>используется для фильтрации предметов по владельцу (например, в профиле пользователя).</li>
     * </ul>
     */
    private Long ownerId;
}

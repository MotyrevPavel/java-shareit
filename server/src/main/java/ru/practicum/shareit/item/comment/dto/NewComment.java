package ru.practicum.shareit.item.comment.dto;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import ru.practicum.shareit.exception.ValidationException;

/**
 * DTO для создания нового комментария к предмету в системе аренды.
 * Используется при:
 * <ul>
 *   <li>отправке HTTP‑запроса на добавление комментария от пользователя;</li>
 *   <li>передаче данных из контроллера в сервисный слой;</li>
 *   <li>валидации входных данных перед сохранением комментария в БД.</li>
 * </ul>
 *
 * <p>Особенности класса:
 * <ul>
 *   <li>содержит только обязательные данные для создания комментария;</li>
 *   <li>не включает метаинформацию (ID, автора, дату создания) — эти данные
 *       добавляются на стороне сервера;</li>
 *   <li>использует {@link Builder} для удобного построения объектов;</li>
 *   <li>поддерживает создание экземпляров через конструктор по умолчанию
 *       и через конструктор со всеми полями благодаря аннотациям
 *       {@link AllArgsConstructor} и {@link NoArgsConstructor}.</li>
 * </ul>
 *
 * @see CommentDto DTO с полной информацией о комментарии (после сохранения)
 */

@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
public class NewComment {

    /**
     * Текст комментария, который пользователь хочет оставить о предмете.
     *
     * <p>Содержит отзыв, оценку или дополнительную информацию, которую автор
     * хочет сообщить другим пользователям или владельцу предмета.
     *
     * <p>Требования к данным:
     * <ul>
     *   <li>обязательное поле — не может быть {@code null};</li>
     *   <li>не должен быть пустой строкой или состоять только из пробелов;</li>
     *   <li>может содержать эмодзи, знаки препинания и переносы строк.</li>
     * </ul>
     *
     * @return текст комментария (строка)
     * @throws ValidationException если текст {@code null}, пустой
     * или состоит только из пробелов
     */
    private String text;
}

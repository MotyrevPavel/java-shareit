package ru.practicum.shareit.request.dto;

import com.fasterxml.jackson.annotation.JsonFormat;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

/**
 * Data Transfer Object (DTO) для представления запроса на аренду предмета в системе.
 * <p>
 * Используется для:
 * <ul>
 *   <li>передачи данных о запросах между слоями приложения;</li>
 *   <li>сериализации/десериализации в JSON при HTTP‑запросах и ответах;</li>
 *   <li>отображения информации о запросах в пользовательском интерфейсе;</li>
 *   <li>формирования ответов API при получении списка или деталей запроса.</li>
 * </ul>
 *
 * <p>Отличается от сущности {@link ru.practicum.shareit.request.ItemRequest} тем, что:
 * <ul>
 *   <li>не содержит бизнес‑логики;</li>
 *   <li>служит исключительно для транспортировки данных;</li>
 *   <li>включает только основные поля, необходимые для клиентского отображения;</li>
 *   <li>автоматически форматирует дату создания в стандартизированном виде через {@link JsonFormat}.</li>
 * </ul>
 *
 * @see ru.practicum.shareit.request.ItemRequest сущность запроса на аренду в системе
 */

@Builder
@Data
@NoArgsConstructor
@AllArgsConstructor
public class ItemRequestDto {

    /**
     * Уникальный идентификатор запроса на аренду.
     *
     * <p>Генерируется автоматически при сохранении запроса в БД. Используется для
     * однозначной идентификации и ссылок в других сущностях (например, при связывании
     * с предложенными предметами).
     *
     * <p>Особенности:
     * <ul>
     *   <li>может быть {@code null} для новых запросов, которые ещё не сохранены в системе;</li>
     *   <li>после сохранения имеет значение типа {@code Long} (например, {@code 123L});</li>
     *   <li>используется в URL API (например, {@code /requests/{id}});</li>
     *   <li>остаётся неизменным на протяжении жизненного цикла запроса.</li>
     * </ul>
     */
    private Long id;

    /**
     * Описание запроса на аренду предмета.
     *
     * <p>Содержит текст, в котором пользователь описывает, какой предмет ему нужен.
     * Позволяет владельцам понять потребности арендатора и предложить подходящий вариант.
     *
     * <p>Требования:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>не должен быть пустой строкой;</li>
     * </ul>
     */
    private String description;

    /**
     * Дата и время создания запроса на аренду.
     *
     * <p>Указывает, когда пользователь создал запрос. Форматируется в JSON
     * по шаблону {@code yyyy-MM-dd'T'HH:mm:ss} (например: {@code 2023-12-25T14:30:15}).
     *
     * <p>Особенности:
     * <ul>
     *   <li>устанавливается автоматически на стороне сервера в момент создания;</li>
     *   <li>не редактируется после установки;</li>
     *   <li>используется для сортировки запросов (новые сверху);</li>
     * </ul>
     *
     * <p>Формат задаётся аннотацией {@link JsonFormat}, что обеспечивает единообразное
     * представление даты в JSON‑ответах API.
     *
     * @see JsonFormat для указания формата даты в JSON
     */
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime created;
}

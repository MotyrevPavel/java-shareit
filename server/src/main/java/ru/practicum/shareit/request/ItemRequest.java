package ru.practicum.shareit.request;

import jakarta.persistence.*;
import lombok.Data;
import ru.practicum.shareit.item.model.Item;
import ru.practicum.shareit.user.model.User;

import java.time.LocalDateTime;
import java.util.List;

/**
 * Сущность (Entity) запроса на аренду предмета в системе ShareIt.
 * <p>
 * Представляет собой модель данных для хранения информации о запросах пользователей
 * на поиск предметов для аренды. Соответствует таблице {@code requests} в базе данных.
 *
 * <p>Основные функции:
 * <ul>
 *   <li>фиксация потребности пользователя в определённом предмете;</li>
 *   <li>хранение описания запроса и времени его создания;</li>
 *   <li>связь с пользователем, создавшим запрос;</li>
 *   <li>отслеживание предметов, предложенных в ответ на запрос.</li>
 * </ul>
 *
 * <p>Особенности реализации:
 * <ul>
 *   <li>использует JPA‑аннотации для маппинга на таблицу БД;</li>
 *   <li>связывается с пользователем через отношение «многие‑к‑одному» ({@code @ManyToOne});</li>
 *   <li>хранит список связанных предметов через отношение «один‑ко‑многим» ({@code @OneToMany});</li>
 *   <li>применяет ленивую загрузку ({@code FetchType.LAZY}) для оптимизации запросов к БД.</li>
 * </ul>
 *
 * @see ru.practicum.shareit.request.dto.ItemRequestDto DTO для передачи данных запроса между слоями
 * @see ru.practicum.shareit.request.dto.ItemRequestWithAnswersDto DTO с запросами и предложенными предметами
 * @see User сущность пользователя системы
 * @see Item сущность предмета для аренды
 */

@Data
@Entity
@Table(name = "requests")
public class ItemRequest {

    /**
     * Уникальный идентификатор запроса на аренду.
     *
     * <p>Генерируется автоматически базой данных при сохранении новой записи.
     * Используется для однозначной идентификации запроса во всех операциях.
     *
     * <p>Особенности:
     * <ul>
     *   <li>первичный ключ таблицы {@code requests};</li>
     *   <li>стратегия генерации — {@code IDENTITY} (автоинкремент);</li>
     *   <li>не может быть {@code null} после сохранения в БД;</li>
     *   <li>используется в URL API (например, {@code /requests/{id}});</li>
     *   <li>остаётся неизменным на протяжении жизненного цикла запроса.</li>
     * </ul>
     *
     * @see GeneratedValue стратегия генерации ID
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Описание запроса на аренду предмета.
     *
     * <p>Текст, в котором пользователь описывает, какой предмет ему нужен.
     * Служит основным источником информации для владельцев при просмотре запросов
     * и формировании предложений.
     *
     * <p>Особенности:
     * <ul>
     *   <li>сохраняется в колонке {@code description} таблицы {@code requests};</li>
     *   <li>не может быть {@code null};</li>
     * </ul>
     *
     * @see Column настройка колонки в БД
     */
    @Column(name = "description", nullable = false)
    private String description;

    /**
     * Дата и время создания запроса.
     * Фиксирует момент, когда пользователь создал запрос. Используется для: сортировки запросов.
     *
     * <p>Особенности:
     * <ul>
     *   <li>сохраняется в колонке {@code created} таблицы {@code requests};</li>
     *   <li>не может быть {@code null};</li>
     *   <li>устанавливается один раз при создании запроса;</li>
     *   <li>тип {@link LocalDateTime} без временной зоны.</li>
     * </ul>
     *
     * @see Column настройка колонки в БД
     */
    @Column(name = "created", nullable = false)
    private LocalDateTime created;

    /**
     * Пользователь, создавший запрос на аренду.
     *
     * <p>Связь «многие‑к‑одному» с сущностью {@link User}. Указывает, кто именно
     * инициировал поиск предмета. Определяет права доступа: только владелец запроса
     * может его редактировать или удалять.
     *
     * <p>Особенности:
     * <ul>
     *   <li>связана с колонкой {@code user_id} в таблице {@code requests};</li>
     *   <li>не может быть {@code null};</li>
     *   <li>загружается лениво ({@code FetchType.LAZY}), чтобы избежать избыточных запросов;</li>
     *   <li>позволяет получить информацию о пользователе (имя, контакты и т. д.).</li>
     * </ul>
     *
     * @see ManyToOne тип отношения JPA
     * @see JoinColumn настройка внешнего ключа
     */

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /**
     * Список предметов, предложенных владельцами в ответ на данный запрос.
     *
     * <p>Связь «один‑ко‑многим» с сущностью {@link Item}. Содержит все предметы,
     * которые могут удовлетворить потребность пользователя, описанную в запросе.
     *
     * <p>Особенности:
     * <ul>
     *   <li>обратная сторона связи задана через {@code mappedBy = "request"};</li>
     *   <li>может быть пустым списком, если пока нет предложений;</li>
     *   <li>загружается лениво ({@code FetchType.LAZY}) для оптимизации производительности;</li>
     *   <li>каждый предмет в списке имеет ссылку на этот запрос ({@code Item.request}).</li>
     * </ul>
     *
     * @see OneToMany тип отношения JPA
     * @see Item сущность предмета для аренды
     */
    @OneToMany(mappedBy = "request", fetch = FetchType.LAZY)
    private List<Item> items;
}
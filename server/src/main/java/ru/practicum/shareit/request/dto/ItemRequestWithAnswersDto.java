package ru.practicum.shareit.request.dto;

import com.fasterxml.jackson.annotation.JsonFormat;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import ru.practicum.shareit.item.dto.ItemShortDto;

import java.time.LocalDateTime;
import java.util.List;

/**
 * Data Transfer Object (DTO) для представления запроса на аренду предмета с перечнем
 * предложенных вариантов от владельцев.
 * <p>
 * Используется для:
 * <ul>
 *   <li>передачи полной информации о запросе вместе с ответами (предложенными предметами);</li>
 *   <li>формирования развёрнутых ответов API при получении деталей запроса;</li>
 *   <li>отображения в пользовательском интерфейсе страницы запроса с доступными предложениями;</li>
 *   <li>сериализации в JSON при HTTP‑ответах, включающих связанные сущности.</li>
 * </ul>
 *
 * <p>Отличается от {@link ItemRequestDto} тем, что:
 * <ul>
 *   <li>содержит список предложенных предметов ({@code items}), отвечающих запросу;</li>
 *   <li>позволяет отобразить всю необходимую информацию на одной странице: сам запрос
 *       и варианты его удовлетворения;</li>
 *   <li>использует {@link ItemShortDto} для компактного представления каждого предложенного предмета.</li>
 * </ul>
 *
 * @see ItemRequestDto базовый DTO с информацией о запросе (без предложений)
 * @see ItemShortDto DTO для краткого представления предмета
 */

@Builder
@Data
@NoArgsConstructor
@AllArgsConstructor
public class ItemRequestWithAnswersDto {

    /**
     * Уникальный идентификатор запроса на аренду.
     *
     * <p>Генерируется автоматически при сохранении запроса в БД. Используется для
     * однозначной идентификации и ссылок в других сущностях.
     *
     * <p>Особенности:
     * <ul>
     *   <li>может быть {@code null} для новых запросов, которые ещё не сохранены в системе;</li>
     *   <li>после сохранения имеет значение типа {@code Long} (например, {@code 123L});</li>
     *   <li>используется в URL API (например, {@code /requests/{id}});</li>
     *   <li>остаётся неизменным на протяжении жизненного цикла запроса.</li>
     * </ul>
     */
    private Long id;

    /**
     * Описание запроса на аренду предмета.
     *
     * <p>Содержит текст, в котором пользователь описывает, какой предмет ему нужен.
     * Позволяет владельцам понять потребности арендатора и предложить подходящий вариант.
     *
     * <p>Требования:
     * <ul>
     *   <li>не может быть {@code null};</li>
     *   <li>не должен быть пустой строкой;</li>
     * </ul>
     */
    private String description;

    /**
     * Дата и время создания запроса на аренду.
     *
     * <p>Указывает, когда пользователь создал запрос. Форматируется в JSON
     * по шаблону {@code yyyy-MM-dd'T'HH:mm:ss} (например: {@code 2023-12-25T14:30:15}).
     *
     * <p>Особенности:
     * <ul>
     *   <li>устанавливается автоматически на стороне сервера в момент создания;</li>
     *   <li>не редактируется после установки;</li>
     *   <li>используется для сортировки запросов (новые сверху);</li>
     * </ul>
     *
     * <p>Формат задаётся аннотацией {@link JsonFormat}, что обеспечивает единообразное
     * представление даты в JSON‑ответах API.
     *
     * @see JsonFormat для указания формата даты в JSON
     */
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime created;

    /**
     * Список предметов, предложенных владельцами в ответ на данный запрос.
     *
     * <p>Содержит краткую информацию о предметах, которые могут удовлетворить
     * потребность пользователя, описанную в запросе. Каждый элемент списка —
     * экземпляр {@link ItemShortDto}.
     *
     * <p>Особенности:
     * <ul>
     *   <li>может быть пустым списком, если пока нет предложений по запросу;</li>
     *   <li>каждый предмет включает минимум данных: ID, название, ID владельца;</li>
     *   <li>позволяет пользователю быстро просмотреть все доступные варианты.</li>
     * </ul>
     *
     * @see ItemShortDto DTO с краткой информацией о предмете
     */
    private List<ItemShortDto> items;
}

package ru.practicum.shareit.request;

import ru.practicum.shareit.exception.NotFoundException;
import ru.practicum.shareit.exception.ValidationException;
import ru.practicum.shareit.request.dto.ItemRequestDto;
import ru.practicum.shareit.request.dto.ItemRequestWithAnswersDto;
import ru.practicum.shareit.request.dto.NewItemRequest;

import java.util.List;

/**
 * Сервис для управления запросами на аренду предметов в системе ShareIt.
 *
 * <p>Предоставляет бизнес‑логику для работы с запросами пользователей на поиск
 * предметов для аренды: создание, получение, фильтрация и обогащение данных.
 *
 * <p>Основные функции:
 * <ul>
 *   <li>создание новых запросов на аренду от имени пользователя;</li>
 *   <li>получение списка запросов пользователя с предложениями предметов;</li>
 *   <li>просмотр запросов других пользователей для предложения своих предметов;</li>
 *   <li>поиск конкретного запроса по ID с детализацией предложений.</li>
 * </ul>
 *
 * <p>Особенности реализации:
 * <ul>
 *   <li>использует DTO‑классы для передачи данных между слоями приложения;</li>
 *   <li>изолирует бизнес‑логику от репозиториев и контроллеров;</li>
 *   <li>обеспечивает валидацию входных данных перед сохранением;</li>
 *   <li>обогащает данные (например, добавляет список предложенных предметов к запросу).</li>
 * </ul>
 *
 * @see NewItemRequest DTO для создания нового запроса (входная модель)
 * @see ItemRequestDto DTO с базовой информацией о запросе
 * @see ItemRequestWithAnswersDto DTO с запросом и списком предложенных предметов
 */

public interface ItemRequestService {

    /**
     * Создаёт новый запрос на аренду предмета от имени указанного пользователя.
     *
     * <p>Обрабатывает входные данные, выполняет валидацию и сохраняет запрос
     * в системе. Возвращает DTO с заполненными системными полями (ID, дата создания).
     *
     * <p>Параметры:
     * <ul>
     *   <li>{@code userId} — идентификатор пользователя, создающего запрос (не может быть {@code null});</li>
     *   <li>{@code newItemRequest} — DTO с описанием запроса ({@link NewItemRequest}, не может быть {@code null}).</li>
     * </ul>
     *
     * <p>Возвращает:
     * <ul>
     *   <li>{@link ItemRequestDto} с заполненными полями: ID запроса, описание, дата создания;</li>
     *   <li>генерирует исключение, если пользователь не найден или данные не прошли валидацию.</li>
     * </ul>
     *
     * @param userId         идентификатор пользователя, создающего запрос
     * @param newItemRequest DTO с описанием запроса на аренду
     * @return {@link ItemRequestDto} заполненный объект с информацией о созданном запросе
     * @throws ValidationException если пользователь с указанным ID не существует
     * @throws ValidationException если описание запроса не соответствует правилам валидации
     */
    ItemRequestDto create(Long userId, NewItemRequest newItemRequest);

    /**
     * Получает все запросы на аренду, созданные указанным пользователем, с детализацией
     * предложенных предметов.
     *
     * <p>Для каждого запроса возвращает список предметов, предложенных владельцами
     * в ответ на запрос. Позволяет пользователю увидеть, какие варианты доступны.
     *
     * <p>Параметр:
     * <ul>
     *   <li>{@code userId} — идентификатор пользователя, чьи запросы нужно получить (не может быть {@code null}).</li>
     * </ul>
     *
     * <p>Возвращает:
     * <ul>
     *   <li>список {@link List}&lt;{@link ItemRequestWithAnswersDto}&gt; — каждый элемент содержит запрос и список предложенных предметов;</li>
     *   <li>пустой список, если пользователь не создавал запросов или к ним нет предложений.</li>
     * </ul>
     *
     * @param userId идентификатор пользователя, чьи запросы необходимо получить
     * @return {@link List}&lt;{@link ItemRequestWithAnswersDto}&gt; список запросов пользователя с предложенными предметами
     */
    List<ItemRequestWithAnswersDto> getAllByUserId(Long userId);

    /**
     * Получает запросы на аренду от всех пользователей, кроме указанного.
     *
     * <p>Используется владельцами предметов для поиска запросов, на которые они могут
     * предложить свои вещи. Не включает запросы самого пользователя.
     *
     * <p>Параметр:
     * <ul>
     *   <li>{@code userId} — идентификатор пользователя, чьи запросы следует исключить (не может быть {@code null}).</li>
     * </ul>
     *
     * <p>Возвращает:
     * <ul>
     *   <li>список {@link List}&lt;{@link ItemRequestDto}&gt; — запросы других пользователей без детализации предложений;</li>
     *   <li>пустой список, если нет запросов от других пользователей.</li>
     * </ul>
     *
     * @param userId идентификатор пользователя, чьи запросы исключаются из результатов
     * @return {@link List}&lt;{@link ItemRequestDto}&gt; список запросов других пользователей
     */
    List<ItemRequestDto> getAllRequestsAnotherUsers(Long userId);

    /**
     * Находит конкретный запрос на аренду по его идентификатору с детализацией
     * предложенных предметов.
     *
     * <p>Возвращает полную информацию о запросе: описание, дату создания и список
     * предметов, предложенных владельцами в ответ на этот запрос.
     *
     * <p>Параметр:
     * <ul>
     *   <li>{@code requestId} — идентификатор запроса, который нужно найти (не может быть {@code null}).</li>
     * </ul>
     *
     * <p>Возвращает:
     * <ul>
     *   <li>{@link ItemRequestWithAnswersDto} — объект с запросом и списком предложенных предметов;</li>
     *   <li>генерирует исключение, если запрос с указанным ID не найден.</li>
     * </ul>
     *
     * @param requestId идентификатор запроса на аренду, который необходимо найти
     * @return {@link ItemRequestWithAnswersDto} заполненный объект с запросом и предложенными предметами
     * @throws NotFoundException если запрос с указанным ID не существует в системе
     * @since 1.0.0
     */
    ItemRequestWithAnswersDto findById(Long requestId);
}

package ru.practicum.shareit.request;

import org.springframework.data.domain.Sort;
import org.springframework.data.jpa.repository.JpaRepository;

import java.util.List;

/**
 * Репозиторий для работы с сущностями запросов на аренду предметов ({@link ItemRequest}).
 *
 * <p>Предоставляет методы для выполнения CRUD‑операций и специализированных запросов
 * к таблице {@code requests} в базе данных через Spring Data JPA.
 *
 * <p>Основные функции:
 * <ul>
 *   <li>поиск запросов по идентификатору пользователя;</li>
 *   <li>получение запросов всех пользователей, кроме указанного;</li>
 *   <li>поддержка сортировки результатов через параметр {@link Sort};</li>
 *   <li>интеграция с Spring Data JPA для автоматической генерации SQL‑запросов.</li>
 * </ul>
 *
 * <p>Особенности реализации:
 * <ul>
 *   <li>наследует все стандартные методы {@link JpaRepository} (save, findById, delete и т.д.);</li>
 *   <li>содержит кастомные методы с семантическими именами, которые Spring Data JPA
 *       преобразует в SQL‑запросы на основе соглашения об именовании;</li>
 *   <li>использует {@link Sort} для гибкой настройки порядка сортировки результатов;</li>
 *   <li>возвращает данные в виде списка {@link List} объектов {@link ItemRequest}.</li>
 * </ul>
 *
 * @see ItemRequest сущность запроса на аренду предмета
 * @see JpaRepository базовый репозиторий Spring Data JPA
 * @see Sort механизм сортировки результатов запросов в Spring Data
 */

public interface ItemRequestRepository extends JpaRepository<ItemRequest, Long> {

    /**
     * Находит все запросы на аренду, созданные указанным пользователем.
     *
     * <p>Выполняет поиск по полю {@code user.id} сущности {@link ItemRequest}.
     * Позволяет пользователю просматривать историю своих запросов или управлять ими.
     *
     * <p>Параметры:
     * <ul>
     *   <li>{@code userId} — идентификатор пользователя, чьи запросы нужно найти (не может быть {@code null});</li>
     *   <li>{@code sort} — объект {@link Sort}, определяющий порядок сортировки результатов
     *       (например, по дате создания в порядке убывания).</li>
     * </ul>
     *
     * <p>Возвращает:
     * <ul>
     *   <li>список {@link List} объектов {@link ItemRequest}, отсортированный согласно параметру {@code sort};</li>
     *   <li>пустой список, если пользователь не создавал запросов.</li>
     * </ul>
     *
     * @param userId идентификатор пользователя, чьи запросы необходимо найти
     * @param sort   объект {@link Sort} с настройками сортировки результатов
     * @return {@link List}&lt;{@link ItemRequest}&gt; список запросов пользователя, отсортированный
     * в соответствии с {@code sort}
     */
    List<ItemRequest> findAllByUserId(Long userId, Sort sort);

    /**
     * Находит все запросы на аренду, созданные пользователями, отличными от указанного.
     *
     * <p>Используется для показа пользователю запросов других людей, чтобы он мог предложить
     * свои предметы в ответ. Исключает запросы самого пользователя из результатов.
     *
     * <p>Параметры:
     * <ul>
     *   <li>{@code userId} — идентификатор пользователя, чьи запросы следует исключить (не может быть {@code null});</li>
     *   <li>{@code sort} — объект {@link Sort}, задающий порядок сортировки возвращаемых запросов.</li>
     * </ul>
     *
     * <p>Возвращает:
     * <ul>
     *   <li>список {@link List} объектов {@link ItemRequest} от других пользователей, отсортированный по {@code sort};</li>
     *   <li>пустой список, если нет запросов от других пользователей.</li>
     * </ul>
     *
     * @param userId идентификатор пользователя, чьи запросы необходимо исключить из результатов
     * @param sort   объект {@link Sort} с настройками сортировки
     * @return {@link List}&lt;{@link ItemRequest}&gt; список запросов других пользователей, отсортированный согласно {@code sort}
     */
    List<ItemRequest> findAllByUser_IdNot(Long userId, Sort sort);
}

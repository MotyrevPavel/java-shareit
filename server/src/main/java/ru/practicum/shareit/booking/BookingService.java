package ru.practicum.shareit.booking;

import ru.practicum.shareit.booking.dto.BookingDto;
import ru.practicum.shareit.booking.dto.NewBooking;
import ru.practicum.shareit.exception.NotFoundException;
import ru.practicum.shareit.exception.ValidationException;

import java.util.List;

/**
 * Сервис для управления бронированиями предметов в системе аренды.
 * Предоставляет бизнес‑логику для создания, подтверждения и получения информации
 * о бронированиях. Обеспечивает проверку прав доступа и валидацию данных.
 * Основные функции:
 * создание новых бронирований;
 * подтверждение или отклонение бронирований владельцами предметов;
 * получение информации о конкретных бронированиях;
 * поиск всех бронирований пользователя или владельца предмета с фильтрацией по статусу.
 * Особенности реализации:
 * проверяет права доступа: пользователь может просматривать только свои бронирования
 * или бронирования своих предметов;
 * выполняет валидацию дат и статусов при создании и подтверждении;
 * возвращает данные в формате DTO ({@link BookingDto}) для передачи между слоями приложения.
 *
 * @see BookingDto DTO с информацией о бронировании для передачи данных
 * @see NewBooking DTO с данными для создания нового бронирования
 * @see BookingState перечисление возможных статусов бронирования
 */
public interface BookingService {

    /**
     * Создаёт новое бронирование предмета.
     * Выполняет следующие действия:
     * валидирует даты бронирования (начало < конец, даты в будущем);
     * проверяет доступность предмета на выбранные даты;
     * создаёт запись о бронировании со статусом {@code WAITING} (ожидает подтверждения);
     * сохраняет бронирование в системе.
     * Пример использования: арендатор хочет забронировать дрель на выходные.
     *
     * @param newBooking DTO с данными бронирования: идентификатор предмета, даты начала и окончания
     *                   (не может быть {@code null})
     * @param bookerId   идентификатор пользователя, создающего бронирование (не может быть {@code null},
     *                   должен соответствовать существующему пользователю)
     * @return {@link BookingDto} с полной информацией о созданном бронировании,
     * включая ID, статус и данные о предмете и арендаторе
     * @throws ValidationException если даты некорректны или предмет недоступен
     * @throws NotFoundException   если предмет с указанным ID не найден
     */
    BookingDto create(NewBooking newBooking, Long bookerId);

    /**
     * Подтверждает или отклоняет бронирование предмета владельцем.
     *
     * <p>Владелец предмета принимает или отклоняет запрос на бронирование.
     * В результате статус бронирования меняется на:
     * <ul>
     *   <li>{@code APPROVED} — если {@code approved = true};</li>
     *   <li>{@code REJECTED} — если {@code approved = false}.</li>
     * </ul>
     *
     * <p>Перед выполнением операции сервис проверяет:
     * <ul>
     *   <li>принадлежность предмета указанному владельцу;</li>
     *   <li>текущий статус бронирования (должен быть {@code WAITING});</li>
     *   <li>существование бронирования с указанным ID.</li>
     * </ul>
     *
     * @param bookingId идентификатор бронирования, которое нужно подтвердить/отклонить
     *                  (не может быть {@code null}, должен соответствовать существующему бронированию)
     * @param approved  флаг подтверждения: {@code true} — подтвердить, {@code false} — отклонить
     * @param ownerId   идентификатор владельца предмета (не может быть {@code null},
     *                  должен иметь право на управление предметом)
     * @return {@link BookingDto} с обновлённым статусом бронирования
     * @throws NotFoundException   если бронирование или предмет не найдены
     * @throws ValidationException если пользователь не является владельцем предмета
     */
    BookingDto approve(Long bookingId, Boolean approved, Long ownerId);

    /**
     * Получает информацию о конкретном бронировании.
     *
     * <p>Возвращает полную информацию о бронировании, включая данные о предмете, арендаторе
     * и статусе. Перед возвратом данных сервис проверяет права доступа:
     * <ul>
     *   <li>пользователь должен быть либо арендатором, либо владельцем предмета;</li>
     *   <li>бронирование должно существовать в системе.</li>
     * </ul>
     *
     * <p>Пример использования: пользователь хочет посмотреть детали своего бронирования.
     *
     * @param bookingId идентификатор бронирования (не может быть {@code null},
     *                  должен соответствовать существующему бронированию)
     * @param userId    идентификатор пользователя, запрашивающего информацию (не может быть {@code null})
     * @return {@link BookingDto} с полной информацией о бронировании
     * @throws NotFoundException   если бронирование не найдено
     * @throws ValidationException если пользователь не имеет доступа к информации о бронировании
     */
    BookingDto getById(Long bookingId, Long userId);

    /**
     * Получает список всех бронирований пользователя с фильтрацией по статусу.
     *
     * <p>Ищет бронирования, созданные указанным арендатором. Поддерживает фильтрацию по статусам:
     * <ul>
     *   <li>{@code ALL} — все бронирования пользователя;</li>
     *   <li>{@code CURRENT} — текущие (в процессе);</li>
     *   <li>{@code PAST} — завершённые;</li>
     *   <li>{@code FUTURE} — будущие;</li>
     *   <li>{@code WAITING} — ожидающие подтверждения;</li>
     *   <li>{@code REJECTED} — отклонённые.</li>
     * </ul>
     *
     * <p>Результаты сортируются по дате начала бронирования в порядке убывания.
     *
     * @param bookerId идентификатор пользователя‑арендатора (не может быть {@code null},
     *                 должен соответствовать существующему пользователю)
     * @param state    статус бронирований для фильтрации ({@link BookingState}, не может быть {@code null})
     * @return список {@link BookingDto} бронирований пользователя, соответствующих критериям поиска
     * (пустой список, если бронирований не найдено)
     * @throws NotFoundException если пользователь с указанным ID не найден
     */
    List<BookingDto> getAllBookingsByBooker(Long bookerId, BookingState state);

    /**
     * Получает список всех бронирований предметов владельца с фильтрацией по статусу.
     *
     * <p>Ищет бронирования для всех предметов, принадлежащих указанному владельцу.
     * Аналогично {@link #getAllBookingsByBooker} поддерживает фильтрацию по статусам.
     *
     * <p>Используется для:
     * <ul>
     *   <li>отображения календаря бронирований всех предметов владельца;</li>
     *   <li>управления подтверждениями бронирований;</li>
     *   <li>анализа активности по арендованным предметам.</li>
     * </ul>
     *
     * <p>Результаты сортируются по дате начала бронирования в порядке убывания.
     *
     * @param ownerId идентификатор владельца предметов (не может быть {@code null},
     *                должен соответствовать существующему пользователю)
     * @param state   статус бронирований для фильтрации ({@link BookingState}, не может быть {@code null})
     * @return список {@link BookingDto} бронирований для предметов владельца,
     * соответствующих критериям (пустой список, если бронирований нет)
     * @throws NotFoundException если владелец с указанным ID не найден
     */
    List<BookingDto> getAllBookingsByOwner(Long ownerId, BookingState state);
}
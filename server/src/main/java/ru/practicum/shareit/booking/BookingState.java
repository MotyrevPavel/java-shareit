package ru.practicum.shareit.booking;

/**
 * Перечисление статусов бронирования в системе аренды предметов.
 * Определяет возможные состояния жизненного цикла бронирования от момента создания
 * до завершения или отмены. Используется для фильтрации и отображения бронирований
 * в пользовательском интерфейсе, а также для контроля бизнес‑логики.
 *
 * <p>Доступные статусы:
 * <ul>
 *   <li>{@code WAITING} — бронирование создано, ожидает подтверждения владельцем;</li>
 *   <li>{@code APPROVED} — владелец подтвердил бронирование;</li>
 *   <li>{@code REJECTED} — владелец отклонил запрос на бронирование;</li>
 *   <li>{@code CANCELED} — арендатор отменил бронирование (до начала периода аренды);</li>
 *   <li>{@code ALL} — специальный статус‑фильтр для получения всех бронирований
 *       без ограничения по статусу.</li>
 * </ul>
 *
 * <p>Особенности использования:
 * <ul>
 *   <li>основные статусы ({@code WAITING}, {@code APPROVED}, {@code REJECTED},
 *       {@code CANCELED}) отражают реальное состояние бронирования;</li>
 *   <li>статус {@code ALL} используется исключительно как параметр фильтрации
 *       в методах сервиса и репозитория;</li>
 *   <li>в базе данных сохраняются только основные статусы (без {@code ALL});</li>
 *   <li>переход между статусами контролируется бизнес‑логикой сервиса
 *       ({@link BookingService}).</li>
 * </ul>
 *
 * @see BookingService сервис управления бронированиями, использующий статусы
 * @see BookingRepository репозиторий, выполняющий поиск по статусам
 */

public enum BookingState {

    /**
     * Бронирование создано арендатором, ожидает подтверждения от владельца предмета.
     *
     * <p>Начальный статус любого нового бронирования. Владелец должен принять или отклонить
     * запрос, прежде чем арендатор сможет использовать предмет.
     *
     * <p>Пример: пользователь забронировал велосипед, запрос отправлен владельцу.
     */
    WAITING,

    /**
     * Владелец подтвердил запрос на бронирование.
     *
     * <p>Бронирование подтверждено и действительно на указанный период. Арендатор может
     * получить предмет в дату начала бронирования.
     *
     * <p>Пример: владелец дрели подтвердил бронирование на 25–30 декабря.
     */
    APPROVED,

    /**
     * Владелец отклонил запрос на бронирование.
     *
     * <p>Арендатор не сможет использовать предмет на выбранные даты. Обычно устанавливается,
     * если предмет уже забронирован или недоступен.
     *
     * <p>Пример: владелец отказал в аренде велосипеда, так как он уже забронирован
     * на запрашиваемые даты.
     */
    REJECTED,

    /**
     * Арендатор отменил бронирование до начала периода аренды.
     *
     * <p>Может быть установлено для бронирований со статусами {@code WAITING}
     * или {@code APPROVED}. Предмет становится доступен для новых бронирований.
     *
     * <p>Пример: арендатор отменил бронь дрели, так как ремонт отложился.
     */
    CANCELED,

    /**
     * Специальный статус‑фильтр для получения всех бронирований без фильтрации по статусу.
     *
     * <p>Используется в методах сервиса ({@link BookingService#getAllBookingsByBooker}
     * и {@link BookingService#getAllBookingsByOwner}) для запроса полного списка
     * бронирований пользователя или владельца.
     *
     * <p><strong>Важно:</strong> этот статус никогда не сохраняется в базе данных
     * как состояние бронирования. Он служит исключительно для фильтрации данных
     * при запросах.
     *
     * <p>Пример: пользователь хочет увидеть все свои бронирования (и ожидающие,
     * и подтверждённые, и отменённые) в одном списке.
     */
    ALL
}

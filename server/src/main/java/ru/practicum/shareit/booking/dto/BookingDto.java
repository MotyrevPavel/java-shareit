package ru.practicum.shareit.booking.dto;

import com.fasterxml.jackson.annotation.JsonFormat;
import lombok.Builder;
import lombok.Data;
import ru.practicum.shareit.item.dto.ItemDto;
import ru.practicum.shareit.user.dto.UserDto;

import java.time.LocalDateTime;

/**
 * DTO для представления информации о бронировании предмета в системе аренды.
 * Используется для:
 * передачи данных о бронировании между слоями приложения;
 * сериализации/десериализации в JSON при HTTP‑запросах;
 * отображения информации о бронировании в пользовательском интерфейсе.
 * Особенности класса:
 * содержит полную информацию о бронировании, включая данные о пользователе и предмете;
 * использует {@link Builder} для удобного создания экземпляров;
 * даты форматируются в стандартизированном формате через {@link JsonFormat}.
 */

@Data
@Builder
public class BookingDto {

    /**
     * Уникальный идентификатор бронирования в системе.
     * Генерируется на стороне сервера при создании записи о бронировании.
     * Может быть null для новых бронирований, которые ещё не сохранены в БД.
     */
    private Long id;

    /**
     * Дата и время начала периода бронирования.
     * Указывает, когда арендатор планирует начать использование предмета.
     * Форматируется в JSON по шаблону "yyyy-MM-dd'T'HH:mm:ss"
     * Требования:
     * может быть null для незавершённых или черновиковых бронирований;
     * должна быть раньше даты окончания бронирования ({@link #end});
     * обычно не может быть в прошлом для активных бронирований.
     */
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime start;

    /**
     * Дата и время окончания периода бронирования.
     * Указывает, когда арендатор планирует вернуть предмет.
     * Форматируется в JSON по тому же шаблону, что и "start".
     * Требования:
     * может быть null для незавершённых бронирований;
     * должна быть позже даты начала бронирования ({@link #start});
     * определяет срок аренды предмета.
     */
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime end;

    /**
     * Текущий статус бронирования.
     * Отражает этап жизненного цикла бронирования в системе. Возможные значения включают:
     * "WAITING" — ожидает подтверждения владельцем;
     * "APPROVED" — подтверждено владельцем;
     * "REJECTED" — отклонено владельцем;
     * "CANCELED" — отменено арендатором;
     * "COMPLETED" — завершено успешно.
     */
    private String status;

    /**
     * Информация о пользователе (арендаторе), который создал бронирование.
     * Содержит основные данные о пользователе в формате {@link UserDto}:
     * идентификатор, имя, email и т.д.
     * Особенности:
     * не может быть null для валидного бронирования;
     * связывает бронирование с конкретным пользователем системы;
     * загружается из сервиса пользователей.
     */
    private UserDto booker;

    /**
     * Информация о предмете, который забронирован.
     * Содержит данные о предмете в формате {@link ItemDto}: идентификатор, название,
     * описание, доступность и т.д.
     * Особенности:
     * не может быть null для валидного бронирования;
     * связывает бронирование с конкретным предметом каталога;
     * загружается из сервиса предметов.
     */
    private ItemDto item;
}
